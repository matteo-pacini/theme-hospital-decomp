#!/usr/bin/env python3
"""Assembly stand-ins: functions whose C source no available compiler
reproduces, matched instead from assembly generated by tools/asm2src.py.

The C stays the source of the function: it keeps its FUNCTION marker and is
still compiled, so a module built into one segment keeps its layout. Next to
it, `<source stem>.standin.s` holds the generated assembly, each function
under a `// STANDIN: 0xADDRESS` marker. When tools/cc.py compiles the
source, the compiled function is renamed `<symbol>.c` (a local symbol,
which the report ignores) and the stand-in's section, symbols and
relocations are added to the object in its place.

Every stand-in is listed in docs/MATCHING.md; they count as matched, not as
decompiled.

Usage: tools/standin.py SOURCE 0xADDRESS   add a stand-in for one function
"""

import os
import re
import struct
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(__file__))
from project import ROOT  # noqa: E402

MARKER = re.compile(r"^//\s*STANDIN:\s*(0x[0-9a-fA-F]+)", re.M)
DOCS = os.path.join(ROOT, "docs", "MATCHING.md")


def companion(source):
    """The stand-in file for a source file (which need not exist)."""
    return os.path.splitext(source)[0] + ".standin.s"


def function_names():
    names = {}
    for line in open(os.path.join(ROOT, "config", "functions.txt")):
        line = line.split("#", 1)[0].split()
        if line:
            names[int(line[0], 16)] = line[2]
    return names


def read_elf(path, Section):
    """Code sections, defined symbols and undefined names of a GNU as object,
    in tools/omf2elf.py's model."""
    b = open(path, "rb").read()
    shoff = struct.unpack_from("<I", b, 0x20)[0]
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", b, 0x2E)
    secs = [struct.unpack_from("<10I", b, shoff + i * shentsize) for i in range(shnum)]
    shstr = secs[shstrndx][4]
    name = lambda tab, off: b[tab + off : b.index(b"\0", tab + off)].decode("latin-1")

    sections = {}
    for i, s in enumerate(secs):
        if s[1] == 1 and s[2] & 4 and s[5]:  # PROGBITS, executable, non-empty
            sec = Section(name(shstr, s[0]), "CODE", max(s[8], 1))
            sec.write(0, b[s[4] : s[4] + s[5]])
            sections[i] = sec

    symtab_i = next(i for i, s in enumerate(secs) if s[1] == 2)
    st = secs[symtab_i]
    strtab = secs[st[6]][4]
    syms, defined, undefined = [], {}, []
    for k in range(st[5] // 16):
        nm, value, _, info, _, shndx = struct.unpack_from("<IIIBBH", b, st[4] + k * 16)
        sname = name(strtab, nm)
        syms.append((sname, value, info, shndx))
        if info >> 4 == 0:
            continue
        if shndx == 0:
            undefined.append(sname)
        elif shndx in sections:
            defined[sname] = (sections[shndx], value, False)

    for s in secs:
        if s[1] != 9 or s[7] not in sections:  # REL for a kept section
            continue
        sec = sections[s[7]]
        for k in range(s[5] // 8):
            off, info = struct.unpack_from("<II", b, s[4] + k * 8)
            sname, value, sinfo, shndx = syms[info >> 8]
            if sinfo & 0xF == 3:  # section symbol
                target = ("sec", sections[shndx])
            else:
                target = ("sym", sname)
            sec.relocs.append((off, info & 0xFF, target))
    return list(sections.values()), defined, undefined


def apply(source, model, Section):
    """Replace the functions of `source` that have stand-ins in the object
    model (sections, symbols, externs, weak) produced by omf2elf.convert;
    return whether there were any."""
    path = os.path.join(ROOT, companion(os.path.relpath(os.path.abspath(source), ROOT)))
    if not os.path.exists(path) or os.environ.get("STANDIN_OFF"):
        return False  # STANDIN_OFF=1: build the C alone, to work on it
    sections, symbols, externs, weak = model
    names = [function_names()[int(m.group(1), 16)] for m in MARKER.finditer(open(path).read())]
    if not names:
        return False
    for name in names:
        if name not in symbols:
            sys.exit(f"{path}: {name} is not compiled from {source}")
    with tempfile.TemporaryDirectory() as tmp:
        obj = os.path.join(tmp, "s.o")
        subprocess.run(["as", "--32", "-o", obj, path], check=True)
        new_sections, defined, undefined = read_elf(obj, Section)

    for name in names:
        new_sec, new_off, _ = defined.pop(name)
        sec, off, _ = symbols[name]
        size = sized(symbols, name)
        if sum(s is sec for s, _, _ in symbols.values()) > 1:
            # A module built into one segment: put the stand-in in the compiled
            # function's place, so jumps between it and its neighbours stay
            # unrelocated displacements, as the original linker resolved them.
            if len(new_sec.data) != size:
                resize(sec, off, size, len(new_sec.data), symbols, name)
            substitute(sec, off, len(new_sec.data), new_sec, symbols)
        else:
            symbols[name + ".c"] = (sec, off, True)
            del symbols[name]
            # The stand-in's records take the compiled function's place in
            # the object's record order.
            new_sec.records = sec.records[:1]
            new_sec.reloc_records = {at: sec.records[0][1] for at, _, _ in new_sec.relocs}
            sections.append(new_sec)
            symbols[name] = (new_sec, new_off, False)
    known = {n for n, _ in externs[1:]}
    externs.extend((n, False) for n in undefined if n not in known and n not in symbols)
    end_before_padding(symbols)
    return True


def end_before_padding(symbols):
    """Give the last function of each code section that ends in alignment
    padding (a stand-in's, or the compiler's before a COMDAT that follows a
    module built into one segment) a local symbol at the padding, so that
    tools/omf2elf.py sizes the function as the executable does."""
    from omf2elf import PADDING

    sizes = {}
    for line in open(os.path.join(ROOT, "config", "functions.txt")):
        line = line.split("#", 1)[0].split()
        if line:
            sizes[line[2]] = int(line[1], 16)
    last = {}
    for name, (sec, off, local) in symbols.items():
        if sec.code and not sec.comdat and not local and off >= last.get(id(sec), (None, -1))[1]:
            last[id(sec)] = (name, off, sec)
    for name, off, sec in last.values():
        end = off + sizes.get(name, len(sec.data))
        if bytes(sec.data[end:]) in PADDING:
            symbols[name + ".pad"] = (sec, end, True)


def sized(symbols, name):
    sec, off, _ = symbols[name]
    ends = [o for s, o, _ in symbols.values() if s is sec and o > off]
    return min(ends, default=len(sec.data)) - off


def resize(sec, off, size, new_size, symbols, name):
    """Make sec[off:off + size] new_size bytes long, moving what follows:
    symbols, relocation sites, section-relative targets, and the resolved
    branches of the other functions that cross the resized range."""
    import capstone

    delta, end = new_size - size, off + size
    moved = lambda a: a + delta if a >= end else a
    relocated = {at + k for at, _, _ in sec.relocs for k in range(4)}
    # Runs of absolute relocations are jump tables, not code.
    table = set()
    abs_sites = sorted(at for at, rtype, _ in sec.relocs if rtype == 1)
    for a, b in zip(abs_sites, abs_sites[1:]):
        if b - a == 4:
            table.update(range(a, b + 4))

    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    starts = sorted({o for s, o, _ in symbols.values() if s is sec} | {len(sec.data)})
    branches = []  # (field offset, field size, target), old positions
    for lo, hi in zip(starts, starts[1:]):
        if lo == off:
            continue
        a = lo
        while a < hi:
            if a in table:
                a += 1
                continue
            ins = next(md.disasm(bytes(sec.data[a:hi]), a, 1), None)
            if ins is None:
                a += 1
                continue
            op = ins.bytes[0]
            rel = op in (0xE8, 0xE9, 0xEB, 0xE3) or 0x70 <= op <= 0x7F or (op == 0x0F and 0x80 <= ins.bytes[1] <= 0x8F)
            if rel:
                width = 1 if op in (0xEB, 0xE3) or 0x70 <= op <= 0x7F else 4
                field = a + ins.size - width
                if field not in relocated:
                    target = int(ins.op_str, 16)
                    branches.append((field, width, a + ins.size, target))
            a += ins.size

    for field, width, next_ins, target in branches:
        if off < target < end:
            sys.exit(f"{name}: a neighbour branches into its middle at {target:#x}")
    sec.data[off:end] = bytes(new_size)
    sec.length += delta
    for field, width, next_ins, target in branches:
        disp = moved(target) - moved(next_ins)
        if width == 1 and not -128 <= disp < 128:
            sys.exit(f"{name}: a short branch at {field:#x} no longer reaches")
        struct.pack_into("<b" if width == 1 else "<i", sec.data, moved(field), disp)

    # A data record that started inside the range starts at its new end.
    sec.records = sorted((moved(o) if o >= end else min(o, off + new_size), n) for o, n in sec.records)
    sec.reloc_records = {moved(at): n for at, n in sec.reloc_records.items() if not off <= at < end}
    relocs = []
    for at, rtype, target in sec.relocs:
        if off <= at < end:
            continue  # replaced with the stand-in's own
        if target[0] == "sec" and target[1] is sec:
            addend = struct.unpack_from("<i", sec.data, moved(at))[0]
            aim = addend + 4 if rtype == 2 else addend
            if aim >= end:
                struct.pack_into("<i", sec.data, moved(at), addend + delta)
        relocs.append((moved(at), rtype, target))
    sec.relocs = relocs
    for n, (s, o, local) in list(symbols.items()):
        if s is sec and o >= end:
            symbols[n] = (s, o + delta, local)


def substitute(sec, off, size, new_sec, symbols):
    """Put new_sec's code over sec[off:off + size] with its relocations."""
    sec.data[off : off + size] = new_sec.data
    sec.relocs = [r for r in sec.relocs if not off <= r[0] < off + size]
    # The stand-in stays in the data record it starts in, so that no record
    # boundary of the compiled code splits one of its relocated fields; the
    # last record that started inside it starts after it.
    inside = [n for o, n in sec.records if off < o <= off + size]
    sec.records = [r for r in sec.records if not off < r[0] <= off + size] + [(off + size, n) for n in inside[-1:]]
    sec.records.sort()
    record = [n for o, n in sec.records if o <= off][-1]
    sec.reloc_records = {at: n for at, n in sec.reloc_records.items() if not off <= at < off + size}
    for at, rtype, target in new_sec.relocs:
        site = off + at
        addend = struct.unpack_from("<i", sec.data, site)[0]
        if target[0] == "sec":
            # A reference into the stand-in itself: now at off in sec.
            struct.pack_into("<i", sec.data, site, addend + off)
            sec.relocs.append((site, rtype, ("sec", sec)))
        elif rtype == 2 and addend != -4 and target[1] in symbols and symbols[target[1]][0] is sec:
            # A branch into the middle of a neighbour in the same section:
            # resolve it, as the linker did. Branches to a function's entry
            # (addend -4) stay relocated, as the compiler emits them.
            struct.pack_into("<i", sec.data, site, symbols[target[1]][1] + addend - site)
        else:
            sec.relocs.append((site, rtype, target))
    sec.reloc_records.update((at, record) for at, _, _ in sec.relocs if off <= at < off + size)


def nonmatching_note(text, marker):
    """The NONMATCHING comment directly above a FUNCTION marker, joined."""
    note = []
    for line in reversed(text[:marker].rstrip("\n").split("\n")):
        if not line.startswith("//"):
            break
        note.insert(0, line[2:].strip())
    note = " ".join(note)
    return note.split("NONMATCHING:", 1)[1].strip() if "NONMATCHING:" in note else ""


def with_layout(body, addr, name):
    """Add to a generated function what the target's section holds around
    it: jump tables placed ahead of its entry, and in a module built into
    one segment, the padding up to the next function."""
    # Imported here: split imports cc, which imports this module.
    from lefile import LEFile
    from project import EXE, Project
    from split import shared_segment
    from x86scan import leading_table

    proj, le = Project(), LEFile(EXE)
    fn = proj.by_name[name]
    unit = next(u for u in proj.units if fn in u.functions)
    table = leading_table(le, fn.addr, fn.end)
    if table is not None:
        lines, a = [f".L{table:08x}:"], table
        while a < fn.addr:
            fx = le.fixups.get(a)
            if fx is None:  # filler between the tables and the entry
                lines.append(f"    .byte {le.read(a, 1)[0]:#04x}")
                a += 1
                continue
            lines.append(f'    .long "{name}"+{fx.target - fn.addr:#x}')
            a += 4
        body = re.sub(r'^(\.type "[^"]*",@function)$', "\n".join(lines) + r"\n\1", body, count=1, flags=re.M)
        body = re.sub(r"\b_C_([0-9a-f]{8})\b",
                      lambda m: f".L{table:08x}+{int(m.group(1), 16) - table:#x}"
                      if table <= int(m.group(1), 16) < fn.addr else m.group(0), body)
    if shared_segment(proj, unit):
        following = [f.addr for f in proj.functions if f.addr > fn.addr]
        pad = le.read(fn.end, min(following) - fn.end) if following else b""
        if pad:
            line = "    .byte " + ", ".join(f"{b:#04x}" for b in pad)
            body = body.replace(f'.size "{name}"', line + f'\n.size "{name}"', 1)
    return body


def add(source, addr):
    """Generate the stand-in for one function and list it in the docs."""
    source = os.path.relpath(os.path.abspath(source), ROOT)
    text = open(os.path.join(ROOT, source), encoding="latin-1").read()
    m = re.search(rf"^//\s*FUNCTION:\s*0x0*{addr:x}\b", text, re.M | re.I)
    if not m:
        sys.exit(f"{source}: no FUNCTION marker for {addr:#x}")
    name = function_names()[addr]
    note = nonmatching_note(text, m.start())

    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, "a.s")
        subprocess.run([sys.executable, os.path.join(ROOT, "tools", "asm2src.py"), out, hex(addr)], check=True, cwd=ROOT)
        generated = open(out).read()
    body = re.sub(r"^// FUNCTION:\s*(0x[0-9a-fA-F]+)", r"// STANDIN: \1", generated.split("\n", 1)[1], flags=re.M)
    body = with_layout(body, addr, name)

    path = os.path.join(ROOT, companion(source))
    if os.path.exists(path):
        if re.search(rf"^//\s*STANDIN:\s*0x0*{addr:x}\b", open(path).read(), re.M | re.I):
            sys.exit(f"{companion(source)}: {addr:#x} already has a stand-in")
        open(path, "a").write(body)
    else:
        head = (".intel_syntax noprefix\n"
                f"// Assembly stand-ins for functions of {os.path.basename(source)} that no available\n"
                "// compiler reproduces; generated by tools/asm2src.py (see tools/standin.py).\n")
        open(path, "w").write(head + body)

    docs = open(DOCS).read()
    entry = f"- `{name}` ({addr:#x}), `{companion(source)}`" + (f": {note.strip()}" if note.strip() else "") + "\n"
    anchor = "\n## Watcom library modules"
    docs = docs.replace(anchor, entry + anchor, 1) if entry not in docs else docs
    open(DOCS, "w").write(docs)
    print(f"{name}: stand-in in {companion(source)}")


if __name__ == "__main__":
    add(sys.argv[1], int(sys.argv[2], 16))
