#!/usr/bin/env python3
"""Assembly stand-ins: functions whose C source no available compiler
reproduces, matched instead from assembly generated by tools/asm2src.py.

The C stays the source of the function: it keeps its FUNCTION marker and is
still compiled, so a module built into one segment keeps its layout. Next to
it, `<source stem>.standin.s` holds the generated assembly, each function
under a `// STANDIN: 0xADDRESS` marker. When tools/cc.py compiles the
source, the compiled function is renamed `<symbol>.c` (a local symbol,
which the report ignores) and the stand-in's section, symbols and
relocations are added to the object in its place.

Every stand-in is listed in docs/MATCHING.md; they count as matched, not as
decompiled.

Usage: tools/standin.py SOURCE 0xADDRESS   add a stand-in for one function
"""

import os
import re
import struct
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(__file__))
from project import ROOT  # noqa: E402

MARKER = re.compile(r"^//\s*STANDIN:\s*(0x[0-9a-fA-F]+)", re.M)
DOCS = os.path.join(ROOT, "docs", "MATCHING.md")


def companion(source):
    """The stand-in file for a source file (which need not exist)."""
    return os.path.splitext(source)[0] + ".standin.s"


def function_names():
    names = {}
    for line in open(os.path.join(ROOT, "config", "functions.txt")):
        line = line.split("#", 1)[0].split()
        if line:
            names[int(line[0], 16)] = line[2]
    return names


def read_elf(path, Section):
    """Code sections, defined symbols and undefined names of a GNU as object,
    in tools/omf2elf.py's model."""
    b = open(path, "rb").read()
    shoff = struct.unpack_from("<I", b, 0x20)[0]
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", b, 0x2E)
    secs = [struct.unpack_from("<10I", b, shoff + i * shentsize) for i in range(shnum)]
    shstr = secs[shstrndx][4]
    name = lambda tab, off: b[tab + off : b.index(b"\0", tab + off)].decode("latin-1")

    sections = {}
    for i, s in enumerate(secs):
        if s[1] == 1 and s[2] & 4 and s[5]:  # PROGBITS, executable, non-empty
            sec = Section(name(shstr, s[0]), "CODE", max(s[8], 1))
            sec.write(0, b[s[4] : s[4] + s[5]])
            sections[i] = sec

    symtab_i = next(i for i, s in enumerate(secs) if s[1] == 2)
    st = secs[symtab_i]
    strtab = secs[st[6]][4]
    syms, defined, undefined = [], {}, []
    for k in range(st[5] // 16):
        nm, value, _, info, _, shndx = struct.unpack_from("<IIIBBH", b, st[4] + k * 16)
        sname = name(strtab, nm)
        syms.append((sname, value, info, shndx))
        if info >> 4 == 0:
            continue
        if shndx == 0:
            undefined.append(sname)
        elif shndx in sections:
            defined[sname] = (sections[shndx], value, False)

    for s in secs:
        if s[1] != 9 or s[7] not in sections:  # REL for a kept section
            continue
        sec = sections[s[7]]
        for k in range(s[5] // 8):
            off, info = struct.unpack_from("<II", b, s[4] + k * 8)
            sname, value, sinfo, shndx = syms[info >> 8]
            if sinfo & 0xF == 3:  # section symbol
                target = ("sec", sections[shndx])
            else:
                target = ("sym", sname)
            sec.relocs.append((off, info & 0xFF, target))
    return list(sections.values()), defined, undefined


def apply(source, model, Section):
    """Replace the functions of `source` that have stand-ins in the object
    model (sections, symbols, externs, weak) produced by omf2elf.convert."""
    path = os.path.join(ROOT, companion(os.path.relpath(os.path.abspath(source), ROOT)))
    if not os.path.exists(path):
        return
    sections, symbols, externs, weak = model
    names = [function_names()[int(m.group(1), 16)] for m in MARKER.finditer(open(path).read())]
    for name in names:
        if name not in symbols:
            sys.exit(f"{path}: {name} is not compiled from {source}")
    with tempfile.TemporaryDirectory() as tmp:
        obj = os.path.join(tmp, "s.o")
        subprocess.run(["as", "--32", "-o", obj, path], check=True)
        new_sections, defined, undefined = read_elf(obj, Section)

    for name in names:
        new_sec, new_off, _ = defined.pop(name)
        sec, off, _ = symbols[name]
        size = sized(symbols, name)
        if len(new_sec.data) == size and sum(s is sec for s, _, _ in symbols.values()) > 1:
            # A module built into one segment: overwrite the compiled function
            # in place, so jumps between it and its neighbours stay unrelocated
            # displacements, as the original linker resolved them.
            substitute(sec, off, size, new_sec, symbols)
        else:
            symbols[name + ".c"] = (sec, off, True)
            del symbols[name]
            sections.append(new_sec)
            symbols[name] = (new_sec, new_off, False)
    known = {n for n, _ in externs[1:]}
    externs.extend((n, False) for n in undefined if n not in known and n not in symbols)


def sized(symbols, name):
    sec, off, _ = symbols[name]
    ends = [o for s, o, _ in symbols.values() if s is sec and o > off]
    return min(ends, default=len(sec.data)) - off


def substitute(sec, off, size, new_sec, symbols):
    """Put new_sec's code over sec[off:off + size] with its relocations."""
    sec.data[off : off + size] = new_sec.data
    sec.relocs = [r for r in sec.relocs if not off <= r[0] < off + size]
    for at, rtype, target in new_sec.relocs:
        site = off + at
        addend = struct.unpack_from("<i", sec.data, site)[0]
        if target[0] == "sec":
            # A reference into the stand-in itself: now at off in sec.
            struct.pack_into("<i", sec.data, site, addend + off)
            sec.relocs.append((site, rtype, ("sec", sec)))
        elif rtype == 2 and addend != -4 and target[1] in symbols and symbols[target[1]][0] is sec:
            # A branch into the middle of a neighbour in the same section:
            # resolve it, as the linker did. Branches to a function's entry
            # (addend -4) stay relocated, as the compiler emits them.
            struct.pack_into("<i", sec.data, site, symbols[target[1]][1] + addend - site)
        else:
            sec.relocs.append((site, rtype, target))


def nonmatching_note(text, marker):
    """The NONMATCHING comment directly above a FUNCTION marker, joined."""
    note = []
    for line in reversed(text[:marker].rstrip("\n").split("\n")):
        if not line.startswith("//"):
            break
        note.insert(0, line[2:].strip())
    note = " ".join(note)
    return note.split("NONMATCHING:", 1)[1].strip() if "NONMATCHING:" in note else ""


def add(source, addr):
    """Generate the stand-in for one function and list it in the docs."""
    source = os.path.relpath(os.path.abspath(source), ROOT)
    text = open(os.path.join(ROOT, source), encoding="latin-1").read()
    m = re.search(rf"^//\s*FUNCTION:\s*0x0*{addr:x}\b", text, re.M | re.I)
    if not m:
        sys.exit(f"{source}: no FUNCTION marker for {addr:#x}")
    name = function_names()[addr]
    note = nonmatching_note(text, m.start())

    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, "a.s")
        subprocess.run([sys.executable, os.path.join(ROOT, "tools", "asm2src.py"), out, hex(addr)], check=True, cwd=ROOT)
        generated = open(out).read()
    body = re.sub(r"^// FUNCTION:\s*(0x[0-9a-fA-F]+)", r"// STANDIN: \1", generated.split("\n", 1)[1], flags=re.M)

    path = os.path.join(ROOT, companion(source))
    if os.path.exists(path):
        if re.search(rf"^//\s*STANDIN:\s*0x0*{addr:x}\b", open(path).read(), re.M | re.I):
            sys.exit(f"{companion(source)}: {addr:#x} already has a stand-in")
        open(path, "a").write(body)
    else:
        head = (".intel_syntax noprefix\n"
                f"// Assembly stand-ins for functions of {os.path.basename(source)} that no available\n"
                "// compiler reproduces; generated by tools/asm2src.py (see tools/standin.py).\n")
        open(path, "w").write(head + body)

    docs = open(DOCS).read()
    entry = f"- `{name}` ({addr:#x}), `{companion(source)}`" + (f": {note.strip()}" if note.strip() else "") + "\n"
    anchor = "\n## Libraries"
    docs = docs.replace(anchor, entry + anchor, 1) if entry not in docs else docs
    open(DOCS, "w").write(docs)
    print(f"{name}: stand-in in {companion(source)}")


if __name__ == "__main__":
    add(sys.argv[1], int(sys.argv[2], 16))
