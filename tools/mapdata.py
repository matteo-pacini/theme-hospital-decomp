#!/usr/bin/env python3
"""Name retail globals after the demo's, using the function pairs from
config/demo_map.txt.

Both builds lay data out in the same order, so within each non-conflicting
function pair whose demo and retail functions reference the same number of
distinct data addresses, the references are paired in address order. Each
pairing votes for the retail address of the demo symbol's start (the retail
reference minus the reference's offset into the demo symbol). A symbol takes
the address that most of its votes agree on.

Writes config/demo_data_map.txt: retail address, demo address, votes,
category, demo size, demo symbol.

Usage: tools/mapdata.py
"""

import bisect
import collections
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import demosyms  # noqa: E402
from lefile import SRC_OFFSET32, LEFile  # noqa: E402
from project import EXE, ROOT  # noqa: E402

MIN_VOTES = 1
MIN_SHARE = 0.6


def data_refs(le, start, end):
    refs = set()
    for site in range(start, end):
        fx = le.fixups.get(site)
        if fx is not None and fx.kind == SRC_OFFSET32 and not le.code.contains(fx.target):
            refs.add(fx.target)
    return refs


def main():
    _, syms = demosyms.load()
    data = sorted((s for s in syms if not s.code and s.addr >= 0x110000), key=lambda s: s.addr)
    data_starts = [s.addr for s in data]
    code_starts = sorted({s.addr for s in syms if s.code and s.addr < 0x100000})

    demo_le = LEFile(demosyms.DEMO_EXE)
    retail_le = LEFile(EXE)
    rows = [l.split() for l in open(os.path.join(ROOT, "config", "demo_map.txt")) if not l.startswith("#")]
    retail_sizes = {}
    for line in open(os.path.join(ROOT, "config", "functions.txt")):
        if not line.startswith("#"):
            a, sz, _ = line.split()
            retail_sizes[int(a, 16)] = int(sz, 16)

    votes = collections.defaultdict(collections.Counter)
    for r, d, _, ev, *_ in rows:
        if ev == "conflict":
            continue
        r, d = int(r, 16), int(d, 16)
        i = bisect.bisect_right(code_starts, d)
        d_end = code_starts[i] if i < len(code_starts) else demo_le.code.base + demo_le.code.vsize
        demo_refs = sorted(data_refs(demo_le, d, d_end))
        retail_refs = sorted(data_refs(retail_le, r, r + retail_sizes[r]))
        if len(demo_refs) != len(retail_refs):
            continue
        for dref, rref in zip(demo_refs, retail_refs):
            j = bisect.bisect_right(data_starts, dref) - 1
            if j >= 0:
                votes[j][rref - (dref - data[j].addr)] += 1

    out = os.path.join(ROOT, "config", "demo_data_map.txt")
    mapped = 0
    with open(out, "w") as f:
        f.write("# retail  demo  votes  category  demo-size  demo-symbol  (generated by tools/mapdata.py)\n")
        for j, c in sorted(votes.items(), key=lambda x: x[1].most_common(1)[0][0]):
            (r, n), total = c.most_common(1)[0], sum(c.values())
            sym = data[j]
            if n < MIN_VOTES or n / total < MIN_SHARE:
                continue
            size = (data_starts[j + 1] if j + 1 < len(data) else sym.addr) - sym.addr
            f.write(f"{r:08x} {sym.addr:08x} {n:5d} {sym.category:<7} {size:6x} {sym.name}\n")
            mapped += 1
    print(f"named {mapped} of {len(data)} demo data symbols", file=sys.stderr)


if __name__ == "__main__":
    main()
