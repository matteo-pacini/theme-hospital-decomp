/* __pascal (callee pops). */
void *AIL_MALLOC(U32 size);
void AIL_FREE(void *ptr);
int AIL_INT386(int intno, union REGS *in, union REGS *out);
#pragma aux (__pascal) AIL_MALLOC "*";
#pragma aux (__pascal) AIL_FREE "*";
