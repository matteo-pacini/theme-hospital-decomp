// A window of the game's 640 x 480 window list (window_list in
// src/wininfo.cpp; struct Window in include/hosp.h). Entry n is requester n
// (Requester in windows.h).
struct WindowDef {
    int16_t x, y;                   // top-left corner on the screen
    uint16_t width, height;         // normal size
    uint16_t min_width, min_height; // size while minimised (flags 0x80)
    uint16_t max_width, max_height; // size while maximised (flags 0x100)
    uint16_t flags;                 // WindowFlags
    int16_t first_button;           // kButtonList index of its first button
    uint8_t draw;                   // n of its reqN_overdraw (src/reqN.cpp), 0 for none
};

// A button of the 640 x 480 button list (button_list in src/wininfo.cpp;
// WindowButtonData in include/hosp.h). Sprites index the requester's sheet.
// No entry is a slider (all max fields are 0), so the slider fields are left
// out.
struct ButtonDef {
    int16_t x, y; // relative to the window
    uint16_t width, height;
    uint32_t flags;          // WindowButtonFlags
    int16_t next;            // kButtonList index of the window's next button, or -1
    uint8_t callback;        // n of its reqN (src/reqN.cpp), 0 for none
    int16_t sprite;          // drawn at x, y
    int16_t pressed_sprite;  // drawn at pressed_x, pressed_y while held or pressed
    int16_t disabled_sprite; // drawn at disabled_x, disabled_y while disabled
    int16_t disabled_x, disabled_y;
    int16_t pressed_x, pressed_y;
};

