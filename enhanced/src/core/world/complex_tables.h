// One step of a patient's action sequence (complex), as the game's Complex
// (include/hosp.h).
struct ComplexStep {
    // Object kind the step needs: the nearest free one is found and the
    // complex fails without one. 0 for none.
    uint8_t object;
    // What the step does (process_person_complex's switch).
    uint8_t action;
    // The action's argument, usually a kPatientAnimStarts column.
    uint16_t anim;
    // If nonzero, the Thing.state set before the action.
    uint8_t state;
    // Extra times the step runs (0 once); negative for a random 1 to -repeat.
    int8_t repeat;
    // Nonzero: the next step runs at once rather than on a later turn.
    uint8_t chain;
};

