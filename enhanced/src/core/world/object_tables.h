// What placing an object needs from the game's objects[] (one entry per
// object kind, ObjectControl in include/hosp.h; data in src/tables.cpp).
struct ObjectInfo {
    std::array<uint8_t, 4> shapes; // kShapes index of the footprint per facing; 0 if it cannot face that way
    uint16_t anim_start;           // anim start of facing 0; facing f uses anim_start + f
    uint8_t category;              // 6 radiator, 7 reception desk, ...
    uint8_t use_style;             // copied to Thing.use_style
    int8_t walls;                  // kObjectWalls group (4 entries, one per facing), or -1
    int8_t next_part;              // kNextParts index of a two-part object's second part, or -1
    uint8_t initial_state;         // Thing.state of a new object
};

// The game's shapes[] (Shapes in include/hosp.h; src/tables.cpp): an
// object's footprint and use tiles as cell offsets (x + y * 128) from its
// cell. The game overlays use_offsets on points[9..14]; mark_object_shape
// relies on that, comparing the footprint points with the use tiles.
struct ShapeInfo {
    uint8_t count;                           // footprint points used
    std::array<int16_t, 9> points;           // footprint
    std::array<int16_t, 6> use_offsets;      // Thing.use_pos[0..5]
    uint8_t use_dx;                          // use_x.tile - x.tile
    uint8_t use_dy;                          // use_y.tile - y.tile
    int8_t depth;                            // Thing.depth
    std::array<uint8_t, 9> point_wall_flags; // per point: bit 0 no wall_n, bit 1 no wall_w allowed
    uint8_t use_wall_flags;                  // the same for use_offsets[0..2]
};

// The game's object_walls[] (ObjectWalls): invisible walls put round an
// object, per object walls group and facing.
struct ObjectWallsInfo {
    uint8_t count;
    std::array<uint16_t, 4> pos; // cell offset from the object's cell
    std::array<uint8_t, 4> side; // 0 wall_n, 1 wall_w
};

// The game's next_part[] (NextPart in src/objects.cpp): the second part of
// a two-part object, its facing and its cell offset per facing of the first.
struct NextPartInfo {
    uint8_t kind;
    std::array<uint8_t, 4> dir;
    std::array<int16_t, 4> offset;
};

